// Helper to get random character that hasn't been assigned yet if possible
export function getRandomCharacter(usedCharacterIds: string[] = []): Character {
  const available = CHARACTERS_POOL.filter(c => !usedCharacterIds.includes(c.id));
  const pool = available.length > 0 ? available : CHARACTERS_POOL;
  const index = Math.floor(Math.random() * pool.length);
  return pool[index];
}
